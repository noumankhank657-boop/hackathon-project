import { useEffect, useRef, useState, type FormEvent } from "react";
import { api } from "../api/hcm";
import { useAuth } from "../auth/AuthContext";
import { Button, Card, EmptyState, ErrorAlert, PageHeading, TextAreaField } from "../components/Feedback";

type ChatMessage = {
  id: string;
  role: "user" | "assistant";
  text: string;
  failureStatus?: number;
};

function messageId() {
  return window.crypto.randomUUID();
}

export function AiAssistantPage() {
  return (
    <>
      <PageHeading title="AI assistant" description="Ask about company policies and data available to your role. Responses are generated by AI." />
      <AiChatPanel />
    </>
  );
}

export function AiChatPanel({ compact = false }: { compact?: boolean }) {
  const { session } = useAuth();
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [input, setInput] = useState("");
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<unknown>(null);
  const bottomRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [messages, pending]);

  async function send(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const message = input.trim();
    if (!message || pending) return;
    const userMessage: ChatMessage = { id: messageId(), role: "user", text: message };
    setMessages((current) => [...current, userMessage]);
    setInput("");
    setPending(true);
    setError(null);
    try {
      const result = await api.ai.chat(message);
      setMessages((current) => [...current, { id: messageId(), role: "assistant", text: result.text }]);
    } catch (reason) {
      setError(reason);
      const status = (reason && typeof reason === "object" && "status" in reason && typeof reason.status === "number")
        ? reason.status
        : undefined;
      const detail = reason instanceof Error ? reason.message : "Unknown error";
      setMessages((current) => [
        ...current,
        {
          id: messageId(),
          role: "assistant",
          text: `The assistant could not answer right now. Please try again shortly. Server message: ${detail}`,
          failureStatus: status,
        },
      ]);
    } finally {
      setPending(false);
    }
  }

  return (
    <Card
      title={compact ? "Ask my assistant" : `Chat with HCM Lite · ${session?.user.role ?? ""}`}
      subtitle="Answers use your role’s permitted data and company policy."
      className={compact ? "" : "min-h-[34rem]"}
    >
      <div className={`flex flex-col ${compact ? "min-h-[20rem]" : "min-h-[27rem]"}`}>
        <div className="flex-1 space-y-3 overflow-y-auto rounded-xl bg-slate-50 p-3 sm:p-4">
          {messages.length === 0 ? (
            <EmptyState title="Ask a question">
              <p>Try asking about attendance, leave balances, payroll summaries, or company policy. Employee accounts only receive answers about their own records.</p>
            </EmptyState>
          ) : messages.map((message) => (
            <article key={message.id} className={`max-w-[95%] rounded-2xl px-4 py-3 text-sm leading-6 ${message.role === "user" ? "ml-auto bg-teal-800 text-white" : "mr-auto border border-slate-200 bg-white text-slate-800"}`}>
              {message.role === "assistant" ? (
                <div className="mb-2 flex items-center gap-2">
                  <span className="rounded-full bg-violet-50 px-2 py-0.5 text-[0.65rem] font-bold uppercase tracking-wide text-violet-800">AI-generated</span>
                  {message.failureStatus ? <span className="text-xs text-rose-700">HTTP {message.failureStatus}</span> : null}
                </div>
              ) : null}
              <p className="whitespace-pre-wrap break-words">{message.text}</p>
            </article>
          ))}
          {pending ? (
            <div className="mr-auto flex items-center gap-2 rounded-2xl border border-slate-200 bg-white px-4 py-3 text-sm text-slate-500" role="status">
              <span className="h-3.5 w-3.5 animate-spin rounded-full border-2 border-teal-700 border-t-transparent" />
              Thinking…
            </div>
          ) : null}
          <div ref={bottomRef} />
        </div>
        {error ? <div className="mt-3"><ErrorAlert message="The previous request failed; you can retry or ask another question." status={(error && typeof error === "object" && "status" in error && typeof error.status === "number") ? error.status : undefined} /></div> : null}
        <form className="mt-3 grid gap-3 sm:grid-cols-[minmax(0,1fr)_auto] sm:items-end" onSubmit={(event) => void send(event)}>
          <TextAreaField
            label="Your question"
            value={input}
            onChange={(event) => setInput(event.target.value)}
            placeholder="Ask a question…"
            maxLength={3000}
            rows={compact ? 2 : 3}
            required
          />
          <Button disabled={pending || !input.trim()}>{pending ? "Sending…" : "Send"}</Button>
        </form>
        <p className="mt-2 text-xs text-slate-400">Do not rely on AI-generated content as a substitute for company policy or a manager’s decision.</p>
      </div>
    </Card>
  );
}
